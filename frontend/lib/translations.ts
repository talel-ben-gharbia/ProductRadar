export function serverT(locale: string, key: string, params?: Record<string, string | number>): string {
  const dict = locale === "fr" ? FR_DICT : EN_DICT
  let text = dict[key]
  if (text === undefined) {
    text = key
  }
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v))
    }
  }
  return text
}
